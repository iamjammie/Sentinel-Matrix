def expand_platforms(s):
    return [PLAT[c] for c in s if c in PLAT]

def build_attack():
    tactics = [{"id":i,"shortname":s,"name":n,"description":d,"order":k} for k,(i,s,n,d) in enumerate(TACTICS)]
    # merge duplicate entries (same technique appearing under multiple tactic blocks)
    merged = {}
    for tid,name,tac,plat,dcs,desc in T:
        tcodes = [TCODE[t] for t in tac.split()]
        if tid in merged:
            m = merged[tid]
            for t in tcodes:
                if t not in m["tactics"]: m["tactics"].append(t)
            for d in dcs.split():
                if d in DC and d not in m["_dc"]: m["_dc"].append(d)
            continue
        merged[tid] = {"id":tid,"name":name,"tactics":tcodes,"platforms":expand_platforms(plat),
                       "_dc":[d for d in dcs.split() if d in DC],"description":desc,
                       "parent": tid.split(".")[0] if "." in tid else None,
                       "is_subtechnique": "." in tid}
    techniques=[]
    for tid,m in merged.items():
        m["data_components"] = [{"id":"DC-"+c,"source":DC[c][0],"component":DC[c][1]} for c in m["_dc"]]
        del m["_dc"]
        m["detection_strategy"] = ("Monitor " + ", ".join(sorted(set(x["component"].lower() for x in m["data_components"]))) + " for patterns associated with " + m["name"].lower() + ".") if m["data_components"] else "Primarily pre-compromise activity; detection relies on external telemetry and threat intelligence."
        techniques.append(m)
    # fix parent names
    names={t["id"]:t["name"] for t in techniques}
    for t in techniques:
        if t["parent"] and t["parent"] in names: t["parent_name"]=names[t["parent"]]
    dcs=[{"id":"DC-"+c,"source":v[0],"component":v[1],"log_source_types":v[2],"windows_event_ids":v[3],"sysmon_event_ids":v[4],"auditd_keys":v[5]} for c,v in DC.items()]
    return {
      "framework":"MITRE ATT&CK Enterprise",
      "dataset_kind":"bundled-compact",
      "note":"Compact dataset authored for offline use. Technique IDs, names, tactic and platform assignments follow ATT&CK Enterprise; descriptions are abbreviated. Import the official MITRE STIX 2.1 bundle (enterprise-attack.json) via Framework Database → Import to load full descriptions and the complete technique list.",
      "version":"compact-15.1",
      "generated_at":datetime.datetime.now(datetime.timezone.utc).isoformat(),
      "tactics":tactics,"techniques":techniques,"data_components":dcs,
      "platforms":sorted(set(PLAT.values())),
      "stats":{"tactics":len(tactics),"techniques":sum(1 for t in techniques if not t["is_subtechnique"]),"subtechniques":sum(1 for t in techniques if t["is_subtechnique"])}
    }

